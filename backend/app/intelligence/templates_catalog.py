# ---- Lookup helpers --------------------------------------------------------
_BY_ID: dict[str, dict[str, Any]] = {t["template_id"]: t for t in TEMPLATES}


def list_templates() -> list[dict[str, Any]]:
    """Return all templates as a plain list. JSON-serialisable."""
    return TEMPLATES


def get_template(template_id: str) -> dict[str, Any] | None:
    """Return a single template by id, or None if not found."""
    return _BY_ID.get(template_id)


def template_metadata_for_llm() -> list[dict[str, Any]]:
    """Compact list for LLM context — drops the heavy theme blob to save tokens."""
    return [
        {
            "template_id": t["template_id"],
            "name": t["name"],
            "tagline": t["tagline"],
            "best_for": t["best_for"],
            "vibe": t["vibe"],
        }
        for t in TEMPLATES
    ]
