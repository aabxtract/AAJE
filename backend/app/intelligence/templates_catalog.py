"""The 15 storefront templates the onboarding LLM can pick from.

Each template is a self-contained JSON-ish dict describing visual identity
(colors, typography), layout intent (hero style, grid, card style), and
suggested content slots (default categories, sample hero text). The LLM
reads the catalog via ``list_templates()`` (in onboarding tools), picks one,
and uses ``finalize_onboarding(template_id=...)`` to lock it in.

Front-end's ``<TemplateRenderer />`` is the single component that consumes
this shape — no per-template React components. To change visual behavior,
edit the JSON here, not React.

Edit guidance:
- Keep `template_id` immutable once a store is published with it.
- `industry_keywords` are matched substring-style against the trader's
  business description; lowercase tokens.
- Hex colors should pair: ensure `primary_color` text on `background` and
  on `card_background` clears AA contrast.
- `sections` array drives section order in the renderer.
"""
